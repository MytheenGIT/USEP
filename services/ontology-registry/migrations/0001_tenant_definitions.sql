-- Tenant label definitions, source configurations and their audit trail (PostgreSQL 14+).
-- Definitions only: no tenant facts here (facts live in the fabric). Mirrors usep.labelling.definitions.LabelDefinition.
-- Tenant isolation is enforced by row-level security: the API must run
--   SELECT set_config('usep.tenant_id', '<tenant uuid from the token>', true);
-- at the start of every transaction. With it unset, no row is visible or writable (deny by default).
-- Rollback: see 0001_tenant_definitions.down.sql.

BEGIN;

CREATE TABLE tenant_label_definition (
    tenant_id       uuid        NOT NULL,
    id              text        NOT NULL CHECK (id ~ '^[a-z][a-z0-9_]{1,62}$'),
    version         integer     NOT NULL DEFAULT 1 CHECK (version >= 1),
    level           text        NOT NULL CHECK (level IN ('industry','organization','application','project')),
    parent_concept  text        NOT NULL,
    namespace       text        NOT NULL DEFAULT 'custom' CHECK (namespace ~ '^[a-z][a-z0-9_.-]{1,62}$'),
    display_name    text        NOT NULL CHECK (length(btrim(display_name)) > 0),
    description     text        NOT NULL DEFAULT '',
    aliases         text[]      NOT NULL DEFAULT '{}' CHECK (cardinality(aliases) <= 20),
    source_systems  text[]      NOT NULL DEFAULT '{}',
    source_types    text[]      NOT NULL DEFAULT '{}',
    "when"          jsonb       NOT NULL DEFAULT '{}'::jsonb,
    properties      jsonb       NOT NULL DEFAULT '[]'::jsonb CHECK (jsonb_typeof(properties) = 'array' AND jsonb_array_length(properties) <= 50),
    relationship_rules text[]   NOT NULL DEFAULT '{}',
    status          text        NOT NULL DEFAULT 'draft' CHECK (status IN ('draft','active','disabled')),
    ontology_version text       NOT NULL,           -- core version it was validated against
    created_by      text        NOT NULL,
    created_at      timestamptz NOT NULL DEFAULT now(),
    updated_by      text        NOT NULL,
    updated_at      timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (tenant_id, id)
);
-- A term is unique per tenant, level and namespace among non-disabled definitions (CC-16).
CREATE UNIQUE INDEX tenant_label_definition_term
    ON tenant_label_definition (tenant_id, level, namespace, lower(display_name)) WHERE status <> 'disabled';

CREATE TABLE source_configuration (
    tenant_id       uuid        NOT NULL,
    id              uuid        NOT NULL,           -- UUID v7 generated by the API
    name            text        NOT NULL CHECK (length(btrim(name)) BETWEEN 1 AND 80),
    git_url         text        NOT NULL CHECK (git_url ~ '^https://' AND length(git_url) <= 2048),
    jira_url text NOT NULL CHECK (jira_url ~ '^https://' AND length(jira_url) <= 2048),
    confluence_url text NOT NULL CHECK (confluence_url ~ '^https://' AND length(confluence_url) <= 2048),
    figma_url text NOT NULL CHECK (figma_url ~ '^https://' AND length(figma_url) <= 2048),
    ad_url text CHECK (ad_url ~ '^(https|ldaps)://' AND length(ad_url) <= 2048),
    status          text        NOT NULL DEFAULT 'submitted' CHECK (status IN ('submitted','processing','ready','failed')),
    status_detail   text,
    created_by      text        NOT NULL,
    created_at      timestamptz NOT NULL DEFAULT now(),
    updated_at      timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (tenant_id, id)
);
-- URLs never carry credentials; secrets are Vault references on the server, never columns here.

CREATE TABLE definition_audit (
    audit_id    bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    tenant_id   uuid        NOT NULL,
    entity      text        NOT NULL CHECK (entity IN ('label_definition','source_configuration')),
    entity_id   text        NOT NULL,
    action      text        NOT NULL CHECK (action IN ('create','update','activate','disable','delete','reset_default')),
    actor       text        NOT NULL,
    at          timestamptz NOT NULL DEFAULT now(),
    before      jsonb,
    after       jsonb
);
CREATE INDEX definition_audit_entity ON definition_audit (tenant_id, entity, entity_id, at);

-- Audit rows are append-only.
CREATE FUNCTION definition_audit_immutable() RETURNS trigger LANGUAGE plpgsql AS
$$ BEGIN RAISE EXCEPTION 'definition_audit is append-only'; END $$;
CREATE TRIGGER definition_audit_no_change BEFORE UPDATE OR DELETE ON definition_audit
    FOR EACH ROW EXECUTE FUNCTION definition_audit_immutable();

-- Row-level security: a row is visible and writable only for the tenant named by usep.tenant_id.
DO $$
DECLARE t text;
BEGIN
  FOREACH t IN ARRAY ARRAY['tenant_label_definition','source_configuration','definition_audit'] LOOP
    EXECUTE format('ALTER TABLE %I ENABLE ROW LEVEL SECURITY', t);
    EXECUTE format('ALTER TABLE %I FORCE ROW LEVEL SECURITY', t);
    EXECUTE format($p$CREATE POLICY tenant_isolation ON %I
        USING (tenant_id = NULLIF(current_setting('usep.tenant_id', true), '')::uuid)
        WITH CHECK (tenant_id = NULLIF(current_setting('usep.tenant_id', true), '')::uuid)$p$, t);
  END LOOP;
END $$;

COMMIT;
